@app.get("/api/analytics/dashboard-summary")
async def dashboard_summary(request: Request):

    # --------------------------------------------------------
    # Authentication check
    # --------------------------------------------------------

    user = get_current_user(request)

    if not user:

        return JSONResponse(
            status_code=401,
            content={
                "success": False,
                "error": "Authentication required."
            }
        )


    try:

        from sqlalchemy import func

        from db.database import (
            SessionLocal,
            Base,
            engine
        )

        from db.models import TravelPlanRecord


        # ----------------------------------------------------
        # Make sure tables exist
        # ----------------------------------------------------

        Base.metadata.create_all(
            bind=engine
        )


        db = SessionLocal()


        try:

            # ------------------------------------------------
            # Total plans
            # ------------------------------------------------

            total_plans = (
                db.query(
                    func.count(TravelPlanRecord.id)
                ).scalar()
                or 0
            )


            # ------------------------------------------------
            # Sentiment scores
            # ------------------------------------------------

            rows = (
                db.query(
                    TravelPlanRecord.sentiment_summary
                )
                .filter(
                    TravelPlanRecord.sentiment_summary.isnot(None)
                )
                .all()
            )


            scores = [

                r[0]["average_score"]

                for r in rows

                if r[0]
                and r[0].get("average_score") is not None

            ]


            # ------------------------------------------------
            # Average sentiment
            # ------------------------------------------------

            avg_sentiment = (

                round(
                    sum(scores) / len(scores),
                    3
                )

                if scores

                else None

            )


            return {

                "total_plans_generated": total_plans,

                "average_review_sentiment": avg_sentiment,

            }


        finally:

            db.close()


    except Exception as e:

        return JSONResponse(
            status_code=502,
            content={
                "error":
                    f"Could not load dashboard summary: {e}"
            },
        )


