@app.post("/api/travel")
async def travel_planner(
    request: Request,
    request_data: TravelRequest
):

    user = get_current_user(request)

    if not user:
        return JSONResponse(
            status_code=401,
            content={
                "success": False,
                "error": "You must be logged in to use TripMate AI."
            }
        )

    try:
        # Import backend ONLY when travel planning is actually requested
        from backend import run_travel_agent

        user_message = request_data.message.strip()

        if not user_message:
            return JSONResponse(
                status_code=400,
                content={
                    "success": False,
                    "error": "Message cannot be empty."
                }
            )

        result = run_travel_agent(
            user_input=user_message,
            thread_id=request_data.thread_id
        )

        return JSONResponse(
            content={
                "success": True,
                "thread_id": result["thread_id"],
                "answer": result["answer"],
                "flight_results": result["flight_results"],
                "hotel_results": result["hotel_results"],
                "weather_results": result["weather_results"],
                "local_info_results": result["local_info_results"],
                "itinerary": result["itinerary"],
                "price_prediction": result["price_prediction"],
                "sentiment_summary": result["sentiment_summary"],
                "recommended_attractions": result["recommended_attractions"],
                "llm_calls": result["llm_calls"],
            }
        )

    except Exception as e:
        print("ERROR:", e)
        traceback.print_exc()

        return JSONResponse(
            status_code=500,
            content={
                "success": False,
                "error": str(e)
            }
        )

