# GOOGLE AUTHENTICATION
# ============================================================

@app.post("/auth/google")
async def google_login(request: Request):

    """
    Receives the Google credential generated by Google Identity
    Services and verifies the ID token.

    If valid:
        - Creates a session
        - Stores basic Google user information
        - Redirects to TripMate

    If invalid:
        - Returns HTTP 401
    """

    try:

        # ----------------------------------------------------
        # Get form data sent by Google
        # ----------------------------------------------------

        form = await request.form()

        credential = form.get("credential")

        if not credential:

            return JSONResponse(
                status_code=400,
                content={
                    "success": False,
                    "error": "Google credential was not provided."
                }
            )


        # ----------------------------------------------------
        # Verify Google ID Token
        # ----------------------------------------------------

        user_info = id_token.verify_oauth2_token(
            credential,
            google_requests.Request(),
            GOOGLE_CLIENT_ID
        )


        # ----------------------------------------------------
        # Extract user information
        # ----------------------------------------------------

        google_user = {
            "google_id": user_info.get("sub"),
            "email": user_info.get("email"),
            "name": user_info.get("name"),
            "picture": user_info.get("picture"),
            "email_verified": user_info.get("email_verified", False)
        }


        # ----------------------------------------------------
        # Check email verification
        # ----------------------------------------------------

        if not google_user["email_verified"]:

            return JSONResponse(
                status_code=403,
                content={
                    "success": False,
                    "error": "Your Google email is not verified."
                }
            )


        # ----------------------------------------------------
        # Store user in session
        # ----------------------------------------------------

        request.session["user"] = google_user


        print(
            f"Google login successful: "
            f"{google_user.get('email')}"
        )


        # ----------------------------------------------------
        # Redirect to TripMate
        # ----------------------------------------------------

        return RedirectResponse(
            url="/",
            status_code=303
        )


    except ValueError as e:

        # Invalid Google token
        print("Google token verification failed:", e)

        return JSONResponse(
            status_code=401,
            content={
                "success": False,
                "error": "Invalid or expired Google authentication token."
            }
        )


    except Exception as e:

        print("Google authentication error:", e)
        traceback.print_exc()

        return JSONResponse(
            status_code=500,
            content={
                "success": False,
                "error": "Google authentication failed."
            }
        )


